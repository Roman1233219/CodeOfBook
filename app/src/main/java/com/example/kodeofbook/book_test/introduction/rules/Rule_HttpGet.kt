package com.example.kodeofbook.book_test.introduction.rules // Пакет правил введения

import java.net.URL // Импорт стандартного инструмента для работы с URL

/**
 * Правило: HTTP GET запрос.
 * Чистый Kotlin способ получения данных из сети без использования сторонних библиотек.
 */
fun Rule_HttpGet(urlString: String): String { // Принимает адрес, возвращает текст или "Error"
    Rule_Logger("Network", ">>> Отправка GET запроса по адресу: $urlString") // Логируем старт сетевой операции
    
    return try { // Попытка выполнить действие, которое может упасть (сеть нестабильна)
        val response = URL(urlString).readText() // Чтение всего текста по указанной ссылке
        Rule_Logger("Network", "<<< Ответ успешно получен. Длина данных: ${response.length}") // Логируем успех
        response // Возвращаем полученный ответ
    } catch (e: Exception) { // Если произошла любая системная или сетевая ошибка
        Rule_Logger("Network", "!!! Сбой сетевого запроса: ${e.message}") // Логируем детали ошибки для дебага
        "Error" // Возвращаем маркер ошибки, чтобы Глава знала о провале
    } // Конец блока перехвата ошибок
} // Конец функции Rule_HttpGet
